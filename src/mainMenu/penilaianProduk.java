    private void btn_SimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_SimpanActionPerformed
        // TODO add your handling code here:
         try {
        Connection conn = koneksi.getKoneksi();
        String sql;

        if (idProdukUpdate == null) {
            // Tambah data baru
            sql = "INSERT INTO tb_dataProduk (namaProduk, kualitas, penjualan, stok, rating) VALUES (?, ?, ?, ?, ?)";
        } else {
            // Update data lama
            sql = "UPDATE tb_dataProduk SET namaProduk = ?, kualitas = ?, penjualan = ?, stok = ?, rating = ? WHERE idProduk = ?";
        }

        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, txt_namaProduk.getText());
        pst.setDouble(2, Double.parseDouble(txt_kualitas.getText()));
        pst.setDouble(3, Double.parseDouble(txt_penjualan.getText()));
        pst.setDouble(4, Double.parseDouble(txt_stok.getText()));
        pst.setDouble(5, Double.parseDouble(txt_rating.getText()));

        if (idProdukUpdate != null) {
            pst.setString(6, idProdukUpdate);
        }

        pst.executeUpdate();

        JOptionPane.showMessageDialog(null, (idProdukUpdate == null) ? "Data berhasil disimpan!" : "Data berhasil diupdate!");

        // Reset form
        txt_namaProduk.setText("");
        txt_kualitas.setText("");
        txt_penjualan.setText("");
        txt_stok.setText("");
        txt_rating.setText("");
        idProdukUpdate = null;

        tampilData();

        // Kembali ke halaman utama
        main_panel.removeAll();
        main_panel.repaint();
        main_panel.revalidate();
        main_panel.add(dataNilaiProduk);
        main_panel.repaint();
        main_panel.revalidate();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_SimpanActionPerformed

    private void btn_editActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_editActionPerformed
        // TODO add your handling code here:
        int selectedRow = tabelData.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(null, "Pilih data yang akan diedit!");
            return;
        }

        // Simpan ID untuk update
        idProdukUpdate = tabelData.getValueAt(selectedRow, 0).toString();
        String namaProduk = tabelData.getValueAt(selectedRow, 1).toString();
        double kualitas = Double.parseDouble(tabelData.getValueAt(selectedRow, 2).toString());
        double penjualan = Double.parseDouble(tabelData.getValueAt(selectedRow, 3).toString());
        double stok = Double.parseDouble(tabelData.getValueAt(selectedRow, 4).toString());
        double rating = Double.parseDouble(tabelData.getValueAt(selectedRow, 5).toString());

        // Isi form input
        txt_namaProduk.setText(namaProduk);
        txt_kualitas.setText(String.valueOf(kualitas));
        txt_penjualan.setText(String.valueOf(penjualan));
        txt_stok.setText(String.valueOf(stok));
        txt_rating.setText(String.valueOf(rating));

        // Tampilkan panel form
        main_panel.removeAll();
        main_panel.repaint();
        main_panel.revalidate();

        main_panel.add(inputNilaiProduk);
        main_panel.repaint();
        main_panel.revalidate();
    }//GEN-LAST:event_btn_editActionPerformed

    private void btn_hapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_hapusActionPerformed
        // TODO add your handling code here:

        int selectedRow = tabelData.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(null, "Pilih data yang akan dihapus!");
            return;
        }

        String id = tabelData.getValueAt(selectedRow, 0).toString();

        int confirm = JOptionPane.showConfirmDialog(null, "Yakin ingin menghapus data ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            try {
                String sql = "DELETE FROM tb_dataProduk WHERE idProduk = ?";
                Connection conn = koneksi.getKoneksi();
                PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, id);
                pst.executeUpdate();

                JOptionPane.showMessageDialog(null, "Data Produk berhasil dihapus.");
                tampilData(); // refresh tabel
            } catch (Exception e) {
                e.printStackTrace();
                JOptionPane.showMessageDialog(null, "Gagal menghapus data: " + e.toString());
            }
        }
    }//GEN-LAST:event_btn_hapusActionPerformed


