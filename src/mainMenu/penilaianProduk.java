    private void tampilData() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("Nama Produk");
        model.addColumn("Kualitas");
        model.addColumn("Jumlah Penjualan");
        model.addColumn("Jumlah Stok");
        model.addColumn("Rating Popularitas");

        try {
            String sql = "SELECT * FROM tb_dataProduk";
            Connection conn = koneksi.getKoneksi();
            Statement stm = conn.createStatement();
            ResultSet res = stm.executeQuery(sql);

            while (res.next()) {
                model.addRow(new Object[]{
                    res.getString("idProduk"),
                    res.getString("namaProduk"),
                    res.getDouble("kualitas"),
                    res.getDouble("penjualan"),
                    res.getDouble("stok"),
                    res.getDouble("rating")
                });
            }

            tabelData.setModel(model);

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Gagal menampilkan data: " + e.toString());
        }
    }

